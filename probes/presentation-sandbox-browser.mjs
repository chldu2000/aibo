import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
import { createServer } from 'vite';
import { chromium } from 'playwright';
const server=await createServer({server:{host:'127.0.0.1',port:0,hmr:false,watch:null}});await server.listen();
const browser=await chromium.launch({headless:true});
const page=await browser.newPage();const evidence=[];
try {
  await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/probes/presentation-sandbox.html`);
  await page.waitForFunction(()=>Boolean(window.sandboxProbe));
  const source=`self.aiboPresentation={async render(input){if(input.data.delay)await new Promise(resolve=>setTimeout(resolve,800));return {tag:'div',key:'root',children:[{tag:'input',key:'draft',attrs:{'aria-label':'Draft',value:input.data.draft||''},events:{input:'draft'}},{tag:'button',key:'send',text:'Send',events:{click:'send'}}]};}};`;
  await page.evaluate(source=>window.sandboxProbe.mount(source,{draft:'saved'}),source);
  let frame=page.frameLocator('iframe');
  await frame.getByRole('textbox',{name:'Draft'}).fill('retained');
  assert.equal(await page.evaluate(()=>window.sandboxProbe.intents.at(-1).value),'retained');
  await page.evaluate(()=>window.sandboxProbe.update({draft:'retained'}));
  await page.waitForFunction(()=>document.querySelector('iframe')?.dataset.presentationRevision==='2');
  assert.equal(await frame.getByRole('textbox',{name:'Draft'}).evaluate(element=>element===document.activeElement),true);
  await frame.getByRole('button',{name:'Send'}).click();
  await page.waitForFunction(()=>window.sandboxProbe.intents.at(-1)?.id==='send');
  assert.equal(await page.evaluate(()=>window.sandboxProbe.intents.at(-1).id),'send');
  assert.equal(await frame.getByRole('textbox',{name:'Draft'}).inputValue(),'retained');
  evidence.push('render, trusted user events and state update');
  const count=await page.evaluate(()=>window.sandboxProbe.intents.length);
  await frame.getByRole('button',{name:'Send'}).evaluate(element=>element.click());
  assert.equal(await page.evaluate(()=>window.sandboxProbe.intents.length),count,'synthetic events cannot invoke host actions');
  evidence.push('untrusted synthetic events rejected; keyed focus survives update');
  await page.evaluate(()=>window.sandboxProbe.update({draft:'next context',delay:true}));
  await frame.getByRole('button',{name:'Send'}).click();
  await page.waitForFunction(()=>document.querySelector('iframe')?.dataset.presentationRevision==='3');
  assert.equal(await page.evaluate(()=>window.sandboxProbe.intents.length),count,'old rendered context cannot dispatch after host revision advances');
  evidence.push('late user event from previous rendered revision rejected');
  const shortcutSource=`self.aiboPresentation={async render(input){if(input.data.delay)await new Promise(resolve=>setTimeout(resolve,800));return {tag:'textarea',key:'editor',attrs:{'aria-label':'Shortcut editor',value:'draft'},primaryEnter:'submit'}}};`;
  await page.evaluate(source=>window.sandboxProbe.mount(source),shortcutSource);
  frame=page.frameLocator('iframe');const editor=frame.getByRole('textbox',{name:'Shortcut editor'});
  const beforeShortcut=await page.evaluate(()=>window.sandboxProbe.intents.length);
  await editor.press('Enter');assert.equal(await editor.inputValue(),'draft\n');
  await editor.evaluate(element=>element.dispatchEvent(new KeyboardEvent('keydown',{key:'Enter',ctrlKey:true,bubbles:true})));
  assert.equal(await page.evaluate(()=>window.sandboxProbe.intents.length),beforeShortcut);
  for(const modifier of ['Control','Meta']){
    await editor.press(modifier+'+Enter');
    await page.waitForFunction(count=>window.sandboxProbe.intents.length===count,beforeShortcut+(modifier==='Control'?1:2));
    assert.equal(await page.evaluate(()=>window.sandboxProbe.intents.at(-1).event),'click');
  }
  const keyboardSession=await page.context().newCDPSession(page);
  await keyboardSession.send('Input.imeSetComposition',{text:'拼音',selectionStart:2,selectionEnd:2});
  await editor.press('Control+Enter');
  assert.equal(await page.evaluate(()=>window.sandboxProbe.intents.length),beforeShortcut+2,'IME composition cannot submit');
  await keyboardSession.send('Input.imeSetComposition',{text:'',selectionStart:0,selectionEnd:0});
  await keyboardSession.detach();
  const shortcutRevision=Number(await page.locator('iframe').getAttribute('data-presentation-revision'));
  await page.evaluate(()=>window.sandboxProbe.update({delay:true}));
  await editor.press('Control+Enter');
  await page.waitForFunction(revision=>Number(document.querySelector('iframe')?.dataset.presentationRevision)>revision,shortcutRevision);
  assert.equal(await page.evaluate(()=>window.sandboxProbe.intents.length),beforeShortcut+2,'stale shortcut cannot submit');
  await assert.rejects(page.evaluate(()=>window.sandboxProbe.mount("self.aiboPresentation={render(){return {tag:'div',key:'bad',primaryEnter:'submit'}}}")),/invalid_presentation_shortcut/);
  evidence.push('primary Enter uses click intent; ordinary Enter inserts newline; IME and stale shortcuts rejected; synthetic keys and invalid shortcut targets rejected');
  const isolated=`self.aiboPresentation={async render(){let network;try{await fetch('https://example.com');network='allowed'}catch{network='blocked'}return {tag:'p',key:'status',text:typeof document+':'+typeof localStorage+':'+typeof __TAURI_INTERNALS__+':'+network};}};`;
  await page.evaluate(source=>window.sandboxProbe.mount(source),isolated);
  assert.equal(await page.frameLocator('iframe').getByText('undefined:undefined:undefined:blocked').count(),1);
  evidence.push('no DOM, storage, Tauri global or network in executable worker');
  await assert.rejects(page.evaluate(()=>window.sandboxProbe.mount("self.aiboPresentation={render(){return {tag:'script',key:'escape',text:'parent.document.body.remove()'}}}")),/invalid_presentation_tree/);
  assert.equal(await page.locator('iframe').count(),1,'failed candidate preserves active frame');
  evidence.push('executable markup rejected and previous frame retained');
  for(const inlineSize of [-1,4097,'20px'])await assert.rejects(page.evaluate(inlineSize=>window.sandboxProbe.mount(`self.aiboPresentation={render(){return {tag:'div',key:'invalid-size',inlineSize:${JSON.stringify(inlineSize)}}}}`),inlineSize),/invalid_presentation_size/);
  evidence.push('layout size hints reject negative, excessive and CSS-string values');
  await assert.rejects(page.evaluate(()=>window.sandboxProbe.abortCandidate()),/preparation_aborted/);
  assert.equal(await page.locator('iframe').count(),1);
  evidence.push('superseded preparation abort removes candidate and preserves active frame');
  await assert.rejects(page.evaluate(()=>window.sandboxProbe.mount("self.aiboPresentation={render(){return {tag:'input',key:'escape',attrs:{onfocus:'alert(1)'}}}}")),/invalid_presentation_attribute/);
  await assert.rejects(page.evaluate(()=>window.sandboxProbe.mount("self.aiboPresentation={render(){return {tag:'img',key:'escape',attrs:{src:'https://example.com'}}}}")),/invalid_presentation_attribute/);
  evidence.push('inline handlers and arbitrary resource URLs rejected');
  await assert.rejects(page.evaluate(()=>window.sandboxProbe.mount('while(true){}')),/timeout|unresponsive/);
  await page.getByRole('button',{name:'Host recovery'}).click();
  assert.equal(await page.evaluate(()=>window.sandboxProbe.recovered),1);
  assert.equal(await page.locator('iframe').count(),0);
  evidence.push('infinite worker terminated; host recovery remains usable');
  const stallsAfterReady="self.aiboPresentation={render(){setTimeout(()=>{while(true){}},100);return {tag:'p',key:'ready',text:'Ready before stall'}}};";
  await page.evaluate(source=>window.sandboxProbe.mount(source),stallsAfterReady);
  await page.waitForFunction(()=>window.sandboxProbe.failures.includes('presentation_worker_unresponsive'),{},{timeout:10000});
  assert.equal(await page.locator('iframe').count(),0);
  await page.getByRole('button',{name:'Host recovery'}).click();
  evidence.push('post-activation infinite loop detected by heartbeat and frame removed');
  await page.evaluate(source=>window.sandboxProbe.mount(source,{draft:'recovered'}),source);
  await page.frameLocator('iframe').getByRole('textbox',{name:'Draft'}).waitFor();
  await page.evaluate(()=>window.sandboxProbe.dispose());
  assert.equal(await page.locator('iframe').count(),0);
  evidence.push('subsequent mount succeeds and disposal removes frames');
  await writeFile('/tmp/aibo-presentation-sandbox-browser.json',JSON.stringify({passed:true,browser:browser.version(),evidence},null,2));
  console.log(JSON.stringify({passed:true,evidence}));
} finally {await browser.close();await server.close();}
