import { defineConfig } from 'vite';
import { svelte } from '@sveltejs/vite-plugin-svelte';
import tailwindcss from '@tailwindcss/vite';
import path from 'node:path';
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';

export default defineConfig({
  plugins: [{
    name: 'aibo-presentation-sandbox-document',
    async configResolved({ root }) {
      const directory = path.join(root, 'public');
      // The frame has an opaque origin. Authorize only this trusted bridge,
      // without relying on engine-specific treatment of script-src 'self'.
      const source = (await readFile(path.join(directory, 'aibo-presentation-sandbox.js'), 'utf8'))
        .replace(/<\/script/gi, '<\\/script');
      const hash = createHash('sha256').update(source).digest('base64');
      const policy = `default-src 'none'; script-src 'sha256-${hash}'; worker-src blob:; style-src 'unsafe-inline'; img-src data:; font-src data:; connect-src 'none'; frame-src 'none'; object-src 'none'; base-uri 'none'; form-action 'none'`;
      const html = `<!doctype html>\n<!-- Generated by vite.config.ts from aibo-presentation-sandbox.js. -->\n<html><head><meta charset="utf-8">\n<meta http-equiv="Content-Security-Policy" content="${policy}">\n<meta name="referrer" content="no-referrer">\n</head><body><div id="root"></div><script>${source}</script></body></html>\n`;
      const filename = path.join(directory, 'aibo-presentation-sandbox.html');
      if (await readFile(filename, 'utf8').catch(() => '') !== html) await writeFile(filename, html);
    },
  }, tailwindcss(), svelte()],
  resolve: {
    alias: {
      $lib: path.resolve('./src/lib'),
    },
  },
  clearScreen: false,
  server: {
    // Keep the Tauri WebView and Vite on the same address family. macOS can
    // resolve `localhost` differently between Node and WebKit, leaving a
    // blank window when Vite only binds to ::1.
    host: '127.0.0.1',
    port: 1420,
    strictPort: true,
    watch: {
      // Tauri compiles Rust into this directory while Vite is running. On
      // Windows, trying to watch a compiler output file that is still locked
      // can make Node's filesystem watcher fail with EBUSY.
      ignored: ['**/node_modules/**', '**/.git/**', '**/src-tauri/target/**'],
    },
  },
  envPrefix: ['VITE_', 'TAURI_'],
});
