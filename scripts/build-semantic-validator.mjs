import { readFile, writeFile } from 'node:fs/promises';
import Ajv from 'ajv';
import standaloneCode from 'ajv/dist/standalone/index.js';
export async function validatorSource() {
  const schema=JSON.parse(await readFile(new URL('../contracts/semantic-view.experimental-v1.schema.json',import.meta.url),'utf8'));
  const ajv=new Ajv({strict:false,allErrors:false,code:{source:true,esm:true}});
  let source=standaloneCode(ajv,ajv.compile(schema));
  // Ajv emits its Unicode length helper as CommonJS even with esm output.
  // Inline code-point counting for native browser ESM; no runtime compiler/eval or CJS interop.
  source=source.replace(/require\("ajv\/dist\/runtime\/ucs2length"\)\.default/g,'ucs2length');
  if(source.includes('require('))throw Error('Unexpected standalone runtime dependency');
  return '// Generated by scripts/build-semantic-validator.mjs. Do not edit.\nfunction ucs2length(value) { let length = 0; for (const character of value) { length++; } return length; }\n'+source+'\n';
}
if(process.argv[1]&&new URL(import.meta.url).pathname===process.argv[1]) await writeFile(new URL('../src/lib/presentation/semantic-view-validator.js',import.meta.url),await validatorSource());
