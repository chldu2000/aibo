import { readFile, writeFile } from 'node:fs/promises';
import Ajv from 'ajv';
import standaloneCode from 'ajv/dist/standalone/index.js';

export async function validatorSource() {
  const schema = JSON.parse(await readFile(new URL('../contracts/presentation-package.v1.schema.json', import.meta.url), 'utf8'));
  const ajv = new Ajv({ strict: false, code: { source: true, esm: true } });
  const source = standaloneCode(ajv, ajv.compile(schema))
    .replace(/require\("ajv\/dist\/runtime\/ucs2length"\)\.default/g, 'ucs2length');
  if (source.includes('require(')) throw Error('Unexpected validator runtime dependency');
  return '// Generated by scripts/build-presentation-validator.mjs. Do not edit.\n'
    + 'function ucs2length(value) { return [...value].length; }\n' + source + '\n';
}

if (process.argv[1] && new URL(import.meta.url).pathname === process.argv[1]) {
  await writeFile(new URL('../packages/presentation-tools/package-validator.js', import.meta.url), await validatorSource());
}
