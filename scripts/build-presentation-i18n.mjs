import {build} from 'esbuild';
import {readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
const output = new URL('../packages/presentation-workbench/i18n.generated.js', import.meta.url);
// The published workbench must not import a sibling repository directory.
// Bundle the canonical pure translator and catalogs so npm tarballs are self-contained.
const result = await build({
  entryPoints:[fileURLToPath(new URL('../packages/i18n/index.js',import.meta.url))],
  bundle:true,write:false,format:'esm',platform:'browser',target:'es2022',minify:true,
  banner:{js:'// Generated by scripts/build-presentation-i18n.mjs. Do not edit.'},
});
const source=result.outputFiles[0].text;
if(process.argv.includes('--check')) {
  if(await readFile(output,'utf8')!==source)throw Error('Presentation translations are stale; run node scripts/build-presentation-i18n.mjs');
} else await writeFile(output,source);
